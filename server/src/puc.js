/** Nivel según los dígitos: 1 clase, 2 grupo, 4 cuenta, 6 subcuenta, 8 auxiliar. */
function levelOf(code) { return code.length; }
function parentOf(code) {
  if (code.length === 8) return code.slice(0, 6);
  if (code.length === 6) return code.slice(0, 4);
  if (code.length === 4) return code.slice(0, 2);
  if (code.length === 2) return code.slice(0, 1);
  return null;
}
function natureOf(code) { return ['1', '5', '6', '7'].includes(code[0]) ? 'D' : 'C'; }

